/**
 * Normalizes raw commodity market records and assigns freshness badges.
 */
export function normalizeMarketPrice(record: Partial<MarketPriceRecord>): MarketPriceRecord {
  const now = new Date();
  const obsDate = record.observationDate ? new Date(record.observationDate) : new Date(0);
  const diffDays = Math.floor((now.getTime() - obsDate.getTime()) / (1000 * 60 * 60 * 24));

  let freshness: 'live' | 'recent' | 'historical' = 'historical';
  if (diffDays <= 1) {
    freshness = 'live';
  } else if (diffDays <= 7) {
    freshness = 'recent';
  }

  return {
    commodityId: record.commodityId || `${(record.commodity || 'crop').toLowerCase()}-${(record.countryCode || 'in').toLowerCase()}`,
    commodity: record.commodity || 'Unknown Commodity',
    countryCode: record.countryCode || 'IN',
    regionCode: record.regionCode,
    city: record.city || 'Regional Center',
    actualMarketName: record.actualMarketName || record.market || 'Wholesale Market',
    marketType: record.marketType || 'wholesale',
    price: Number(record.price) || 0,
    unit: record.unit || 'kg',
    trend: record.trend || 'stable',
    change: Number(record.change) || 0,
    market: record.market || record.actualMarketName || 'Regional Wholesale Market',
    state: record.state || 'National',
    observationDate: record.observationDate || 'Date unavailable',
    source: record.source || 'Agmarknet / DMI',
    sourceURL: record.sourceURL || 'https://agmarknet.gov.in',
    freshness,
    currency: record.currency || 'INR',
    verificationStatus: record.verificationStatus || 'verified',
  };
}

/**
 * Loads verified commodity prices with provenance for a specific country.
 * If countryCode is provided, strictly isolates observations from that country.
 * Does not fall back to Indian Mandi records for European / Western countries.
 */
export async function getMarketPrices(countryCode?: SupportedRegion): Promise<MarketPriceRecord[]> {
  const allRecords = VERIFIED_BENCHMARK_PRICES.map(normalizeMarketPrice);
  if (!countryCode) {
    return allRecords;
  }
  return allRecords.filter((record) => record.countryCode === countryCode);
}
