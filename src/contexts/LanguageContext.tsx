/** Supported languages */
export type Lang = "en" | "hi" | "mr" | "ta" | "de" | "pl" | "fr" | "es" | "te" | "ar";

/** Context shape (keeps old & new names to avoid breaking anything) */
type Ctx = {
  // NEW API
  lang: Lang;
  setLang: (l: Lang) => void;
  // Legacy aliases (so older code keeps working)
  language: Lang;
  setLanguage: (l: Lang) => void;
  // translator
  t: (key: string) => string;
};

const LanguageContext = createContext<Ctx | undefined>(undefined);

/** Normalize browser codes like en-US → en, mr-IN → mr */
const normalize = (v?: string | null): Lang => {
  const base = (v || "en").toLowerCase().split("-")[0] as Lang;
  return (["en", "hi", "mr", "ta", "de", "pl", "fr", "es", "te", "ar"] as const).includes(base)
    ? base
    : "en";
};

/** Safe nested getter using dot notation ("footer.brand") */
export const pathGet = (obj: any, path: string) =>
  path.split(".").reduce((acc, k) => (acc ? acc[k] : undefined), obj);

