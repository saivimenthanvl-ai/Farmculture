/** ---------------- Provider ---------------- */
export const LanguageProvider: React.FC<PropsWithChildren> = ({ children }) => {
  // Sync with LocalizationContext preferences stored under PREFS_STORAGE_KEY
  const getInitialLang = (): Lang => {
    if (typeof localStorage !== "undefined") {
      try {
        const storedPrefs = localStorage.getItem("farmculture_user_preferences_v1");
        if (storedPrefs) {
          const parsed = JSON.parse(storedPrefs);
          if (parsed.interfaceLocale) {
            return normalize(parsed.interfaceLocale);
          }
        }
        const legacy = localStorage.getItem("lang");
        if (legacy) return normalize(legacy);
      } catch {
        // fallback
      }
    }
    return normalize(typeof navigator !== "undefined" ? navigator.language : "en");
  };

  const [lang, setLangState] = useState<Lang>(getInitialLang);

  const setLang = (newLang: Lang) => {
    const normalized = normalize(newLang);
    setLangState(normalized);
    if (typeof localStorage !== "undefined") {
      localStorage.setItem("lang", normalized);
    }
  };

  // Listen to cross-context language change notifications
  useEffect(() => {
    const handleStorageChange = () => {
      setLangState(getInitialLang());
    };
    window.addEventListener("farmculture-locale-change", handleStorageChange);
    window.addEventListener("storage", handleStorageChange);
    return () => {
      window.removeEventListener("farmculture-locale-change", handleStorageChange);
      window.removeEventListener("storage", handleStorageChange);
    };
  }, []);

  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang;
      document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    }
  }, [lang]);

  // translator supports flat keys & dot-notation with English fallback
  const t = useMemo(() => {
    const table = dict[lang] || dict.en;
    const fallbackTable = dict.en;

    return (key: string) => {
      const v = pathGet(table, key) ?? table[key];
      if (typeof v === "string") return v;

      // Fallback to English dictionary
      const fb = pathGet(fallbackTable, key) ?? fallbackTable[key];
      if (typeof fb === "string") return fb;

      // Dev-only fallback warning: logs in console, never shows raw key symbol in production UI
      if (import.meta.env?.DEV) {
        console.warn(`[i18n] ⚠ key missing: "${key}" (lang: ${lang})`);
      }
      return key.split(".").pop() || key;
    };
  }, [lang]);

  const value = useMemo<Ctx>(
    () => ({
      lang,
      setLang,
      language: lang, // legacy alias
      setLanguage: setLang, // legacy alias
      t,
    }),
    [lang, t]
  );

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
};

/** Hook */
export const useLanguage = () => {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used within LanguageProvider");
  return ctx;
};

