for (const [lang, map] of Object.entries(navEntries)) {
  const targetPattern = '  ' + lang + ': {';
  const pos = content.indexOf(targetPattern);
  if (pos !== -1) {
    let injection = '\n';
    for (const [k, v] of Object.entries(map)) {
      injection += '    "' + k + '": ' + JSON.stringify(v) + ',\n';
    }
    content = content.slice(0, pos + targetPattern.length) + injection + content.slice(pos + targetPattern.length);
    console.log('Injected keys for', lang);
  }
}

